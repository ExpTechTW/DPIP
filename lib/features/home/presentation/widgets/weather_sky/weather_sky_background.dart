/// GPU-rendered layered sky backdrop, ported from the reference engine.
///
/// The scene is driven the way the original is: a ring of authored keyframes
/// per weather type (`sky_keyframe_data.dart`) supplies the atmosphere, and a three-stage scattering pipeline
/// (`shaders/sky/`) bakes that into two lookup tables the screen pass simply
/// reads. There is no simulated sun — `sunAngleY` *is* the sky LUT's u
/// coordinate. The ring is anchored to the real sunrise and sunset for the
/// viewer's latitude, so dawn keyframes land at dawn year-round.
///
/// Clouds are authored volumetric sprites with baked normal maps
/// (`assets/weather/clouds/`, generated by `tool/gen/cloud_sprites.py`), lit by
/// sampling the sky LUT — the environment-light model, and the reason
/// cloud colour always agrees with the sky behind it.
///
/// Cost is controlled by structure: the scattering integral runs only when the
/// resolved keyframe changes (minutes apart, not frames), precipitation and
/// lightning render at [_renderScale] and are upscaled, and the cloud deck
/// has its own slower, smaller target ([SkyDeck]). The picture itself is
/// repainted on [skyFrameInterval]. Between paints the ticker is stopped,
/// so the engine is not asked for a frame. Each layer gates itself on its
/// own control.
///
/// [mode] forces a look; [active] holds the last frame when the backdrop is
/// off-screen to save GPU.
class WeatherSkyBackground extends StatefulWidget {
  /// Which weather look to render.
  final WeatherMode mode;

  /// Overrides the look's default rain amount (0..1 on the painter's ladder:
  /// 0.321 小雨 → 1.0 暴雨) when a live code carries one; `null` keeps the
  /// look's own default.
  final double? rainIntensity;

  /// Overrides the look's default snow amount (0..1); `null` keeps the look's.
  final double? snowIntensity;

  /// Whether the animation should run.
  final bool active;

  /// Viewer latitude, for anchoring the keyframe ring to the real day.
  final double latitude;

  /// Viewer longitude.
  final double longitude;

  /// Relative humidity 0..1, which blends each keyframe's atmosphere ramps.
  final double humidity;

  /// Pins the sky to a point in the day, or follows the clock on
  /// [SkyTimeMode.auto].
  final SkyTimeMode timeMode;

  const WeatherSkyBackground({
    super.key,
    this.mode = WeatherMode.auto,
    this.rainIntensity,
    this.snowIntensity,
    this.active = true,
    this.latitude = kTaiwanLatitude,
    this.longitude = kTaiwanLongitude,
    this.humidity = 0.65,
    this.timeMode = SkyTimeMode.auto,
  });

  @override
  State<WeatherSkyBackground> createState() => _WeatherSkyBackgroundState();

  /// How early the pace timer wakes, so the next vsync lands near the due
  /// time. A 120 Hz frame is about 8 ms; waking 6 ms ahead skips the vsync
  /// that would still be early and catches the one that is due.
  @visibleForTesting
  static const Duration paceLead = Duration(milliseconds: 6);

  /// Seconds the sky clock reads in tests. Null in the app.
  ///
  /// Frames are timed with a [Stopwatch], which a widget test cannot
  /// advance, so the `dt` of a skipped vsync could not be asserted. Tests
  /// assign this and move the value. Production leaves it null, and the
  /// stopwatch stays the time base the particles already integrate against.
  @visibleForTesting
  static double Function()? debugFrameNow;
}

class _WeatherSkyBackgroundState extends State<WeatherSkyBackground>
    with SingleTickerProviderStateMixin {
  /// Internal render resolution as a fraction of the widget's size.
  ///
  /// The reference rasterises everything before layer 8 — sky, galaxy, clouds
  /// — at **half** device resolution and the deferred layers at 0.75, then
  /// upscales. Precipitation and lightning stay at 0.75 because a streak
  /// softens badly below that. The cloud deck is not on this scale: it is
  /// [kSkyDeckScale] of the screen, updated at [kSkyDeckPeriod]. The low
  /// tier draws the fast layers at 0.6 and leaves the sky picture on the
  /// vsync clock. Near rain falls 2.25–2.60 screen-heights a second, so a
  /// 30 fps step is about 8% of the screen and reads as stepping. A 30 fps
  /// offscreen copy of the sky and night was measured on a low-tier emulator
  /// and raised CPU (clear noon about 13% to 19%, clear night about 13% to
  /// 18%): the gradient is already one image, the night pass is one sample,
  /// and copying that image 30 times a second cost more than drawing it.
  /// Rain also has to stay in this picture — it is [BlendMode.plus] against
  /// the sky, and a second layer would composite the drops over the sky
  /// instead of adding them to it.
  static const double _renderScaleHigh = 0.75;
  static const double _renderScaleLow = 0.6;

  /// One deck for the life of the backdrop. The painter is rebuilt every
  /// tick; the images must not be.
  final SkyDeck _deck = SkyDeck();

  /// The device tier, resolved once before the particles are built (their
  /// pools depend on it). Null only while the first tier probe is in flight;
  /// the backdrop holds its flat fallback colour until [_load] lands.
  RenderTier? _tier;

  /// Number of cloud sprites in `assets/weather/clouds/`.
  static const int _spriteCount = 12;

  static const List<String> _bakeAssets = [
    'shaders/sky/transmittance.frag',
    'shaders/sky/sky_lut.frag',
  ];

  static const List<String> _layerAssets = [
    WeatherSkyPainter.nightAsset,
    WeatherSkyPainter.nightFieldAsset,
    WeatherSkyPainter.cloudsAsset,
    WeatherSkyPainter.lightningAsset,
    WeatherSkyPainter.sunFlareAsset,
    WeatherSkyPainter.rainbowAsset,
  ];

  final Stopwatch _clock = Stopwatch();
  late final AnimationController _ticker = AnimationController(
    duration: const Duration(seconds: 60),
    vsync: this,
  );

  final Map<String, ui.FragmentShader> _shaders = {};
  final List<ui.Image> _sprites = [];
  final List<ui.Image> _sunTextures = [];
  SkyLutCache? _lutCache;
  PrecipitationField? _rain;
  PrecipitationField? _snow;

  /// Seconds of the last frame that was actually painted.
  ///
  /// Skipped vsyncs leave this alone. The next painted frame's `dt` is the
  /// whole gap, which is what keeps rain and snow at the speed they had
  /// when every vsync painted.
  double _lastFrameSeconds = 0;

  /// Weather or [WeatherSkyBackground.active] changed since the last paint.
  ///
  /// The next builder invocation paints even when the pace interval has not
  /// elapsed, then clears this. Waiting the interval out would hold the old
  /// sky — a clear frame after the rain had started, or a frozen one after
  /// the sheet returned to the top. Setting this also drops the pace timer
  /// so that frame is not deferred.
  bool _paintNow = false;

  /// One timer between paints. While it is pending the ticker is stopped,
  /// so the engine is not asked for a frame.
  Timer? _paceTimer;

  /// The scene the current build handed the post-frame callback. The
  /// callback decides the wait; build only records it.
  Duration _paceInterval = Duration.zero;
  double _paceSincePaint = 0;
  bool _pacePainted = false;
  bool _paceCallbackScheduled = false;

  /// Last [TickerMode] value. Null until the first dependency resolution.
  /// A disabled mode is the same as [WeatherSkyBackground.active] false:
  /// the ticker, the clock and the pace timer all stop, and the timer
  /// must not start them again.
  bool? _tickerModeEnabled;

  /// The painter from the last painted frame. Reused while the animation is
  /// stopped and while the pace interval has not elapsed, so a rebuild does
  /// not repaint the sky (see the [CustomPaint] construction in build).
  WeatherSkyPainter? _lastPainter;

  /// UTC day of the cached [_sun] / [_moon] (sunrise/sunset move ~1 min
  /// per day; the moon phase by ~2.5 % per day — frame-level recomputation is
  /// pure waste, and day-level caching keeps them exact for a whole session).
  int _dayKey = -1;
  ({double sunrise, double sunset}) _sun = (sunrise: 5.6, sunset: 18.4);
  double _moon = 0;

  /// Local minute of the cached [_position] / [_sky]. The keyframe ring only
  /// advances ~17 frames over a day, so one tick a minute is ~1/85,000 of the
  /// ring — far below the LUT's own resolution. Batching to the minute means
  /// the scattering bake (256×256 + 256×141 rasterise + CPU readback +
  /// gradient rebuild) runs once a minute instead of once a second, which is
  /// the difference between a cheap backdrop and one that drops a frame
  /// mid-animation on a low-end GPU.
  int _minuteKey = -1;
  double _position = 0;
  ResolvedSky? _sky;

  @override
  void initState() {
    super.initState();
    // repeat() asks for another frame when this notification returns, which
    // is still the transient-callback phase. A post-frame stop is too late:
    // the engine frame is already requested, and cancelling the callback
    // does not clear that request. Stopping here is what leaves no frame
    // scheduled. The post-frame callback arms the timer once build has
    // decided how long to wait.
    _ticker.addListener(_haltAfterTick);
    _init();
  }

  void _haltAfterTick() {
    _ticker.stop();
  }

  /// Resolves the device tier, then loads shaders/sprites/particles — the
  /// particle pools and render scale depend on the tier, so it must land
  /// first. A tier probe failure keeps full quality (never degrade an
  /// experience on a measurement we didn't get).
  Future<void> _init() async {
    RenderTier tier;
    try {
      tier = renderTierFor(await DeviceInfoService.load());
    } catch (error, stackTrace) {
      Log.handle(error, stackTrace, 'Device tier probe failed');
      tier = RenderTier.high;
    }
    if (!mounted) return;
    _tier = tier;
    await _load();
  }

  Future<void> _load() async {
    final layers = <String, ui.FragmentShader>{};
    final bakers = <String, ui.FragmentShader>{};

    for (final asset in [..._bakeAssets, ..._layerAssets]) {
      try {
        final program = await ui.FragmentProgram.fromAsset(asset);
        final shader = program.fragmentShader();
        if (_bakeAssets.contains(asset)) {
          bakers[asset] = shader;
        } else {
          layers[asset] = shader;
        }
      } catch (error, stackTrace) {
        Log.handle(error, stackTrace, 'Failed to load shader $asset');
      }
    }

    ui.Image? rainAtlas;
    ui.Image? snowAtlas;
    for (final entry in const [
      ('assets/weather/particles/rain_drop.webp', true),
      ('assets/weather/particles/snow_flake.webp', false),
    ]) {
      try {
        final image = await _decodeAsset(entry.$1);
        if (entry.$2) {
          rainAtlas = image;
        } else {
          snowAtlas = image;
        }
      } catch (error, stackTrace) {
        Log.handle(
          error,
          stackTrace,
          'Failed to load particle sprite ${entry.$1}',
        );
      }
    }

    final sunTex = <ui.Image>[];
    for (final path in const [
      'assets/weather/sky/sun_profile.webp',
      'assets/weather/sky/sun_rays.webp',
      'assets/weather/sky/annulus.webp',
    ]) {
      try {
        sunTex.add(await _decodeAsset(path));
      } catch (error, stackTrace) {
        Log.handle(error, stackTrace, 'Failed to load sun texture $path');
      }
    }

    final sprites = <ui.Image>[];
    for (var i = 0; i < _spriteCount; i++) {
      final path = 'assets/weather/clouds/${i.toString().padLeft(2, '0')}.webp';
      try {
        sprites.add(await _decodeAsset(path));
      } catch (error, stackTrace) {
        Log.handle(error, stackTrace, 'Failed to load cloud sprite $path');
      }
    }

    if (!mounted) {
      for (final s in [...layers.values, ...bakers.values]) {
        s.dispose();
      }
      for (final image in sprites) {
        image.dispose();
      }
      rainAtlas?.dispose();
      snowAtlas?.dispose();
      for (final t in sunTex) {
        t.dispose();
      }
      return;
    }

    final transmittance = bakers[_bakeAssets[0]];
    final skyLut = bakers[_bakeAssets[1]];

    setState(() {
      _disposeResources();
      _shaders
        ..addAll(layers)
        ..addAll(bakers);
      _sprites.addAll(sprites);
      _sunTextures.addAll(sunTex);
      // Without both bake shaders there is no sky; the fallback colour shows.
      _lutCache = (transmittance != null && skyLut != null)
          ? SkyLutCache(transmittance, skyLut)
          : null;
      // The rain atlas packs four width variants; snow is a single cell.
      final lowEnd = _tier == RenderTier.low;
      _rain = rainAtlas == null
          ? null
          : PrecipitationField(
              atlas: rainAtlas,
              // Lighter rain uses a fraction of this pool. The high tier is one
              // preset under the authored storm (see
              // [PrecipitationField.highRainCapacity]); the low tier stays on
              // the smaller pool.
              capacity: lowEnd
                  ? PrecipitationField.lowRainCapacity
                  : PrecipitationField.highRainCapacity,
              variants: 4,
              cell: const Size(32, 68),
              seed: 7,
            );
      _snow = snowAtlas == null
          ? null
          : PrecipitationField(
              atlas: snowAtlas,
              capacity: lowEnd
                  ? PrecipitationField.lowSnowCapacity
                  : PrecipitationField.highSnowCapacity,
              cell: const Size(40, 40),
              tumble: true,
              seed: 11,
            );
    });
    _syncRunning();
  }

  static Future<ui.Image> _decodeAsset(String path) async {
    final data = await rootBundle.load(path);
    final codec = await ui.instantiateImageCodec(data.buffer.asUint8List());
    try {
      return (await codec.getNextFrame()).image;
    } finally {
      codec.dispose();
    }
  }

  void _disposeResources() {
    _lutCache?.dispose();
    _lutCache = null;
    for (final shader in _shaders.values) {
      shader.dispose();
    }
    _shaders.clear();
    for (final image in _sprites) {
      image.dispose();
    }
    _sprites.clear();
    for (final t in _sunTextures) {
      t.dispose();
    }
    _sunTextures.clear();
    _rain?.atlas.dispose();
    _snow?.atlas.dispose();
    _rain = null;
    _snow = null;
  }

  bool get _ready =>
      _lutCache != null && _shaders.length >= _layerAssets.length;

  /// `active`, a loaded scene, and [TickerMode] all have to agree. The sheet
  /// gate stops the sky by clearing `active`; an offstage route does it with
  /// [TickerMode]. Either one drops the ticker, the clock and the timer.
  bool get _shouldRun =>
      widget.active && _ready && (_tickerModeEnabled ?? false);

  void _syncRunning() {
    if (_shouldRun) {
      _cancelPace();
      if (!_clock.isRunning) _clock.start();
      // This runs inside a frame that is already scheduled (load, resume,
      // or a ticker-mode change). repeat() would ask for the next frame
      // too, and stopping the ticker after the frame does not clear that
      // request. The pace timer is what starts the ticker again.
    } else {
      _cancelPace();
      if (_clock.isRunning) _clock.stop();
      _ticker.stop();
    }
  }

  void _cancelPace() {
    _paceTimer?.cancel();
    _paceTimer = null;
  }

  @override
  void didChangeDependencies() {
    super.didChangeDependencies();
    final enabled = TickerMode.valuesOf(context).enabled;
    if (enabled == _tickerModeEnabled) return;
    _tickerModeEnabled = enabled;
    _syncRunning();
  }

  @override
  void didUpdateWidget(WeatherSkyBackground oldWidget) {
    super.didUpdateWidget(oldWidget);
    final resumed = !oldWidget.active && widget.active;
    final weatherChanged =
        oldWidget.mode != widget.mode ||
        oldWidget.rainIntensity != widget.rainIntensity ||
        oldWidget.snowIntensity != widget.snowIntensity;
    if (oldWidget.active != widget.active) _syncRunning();
    if (weatherChanged || resumed) {
      _paintNow = true;
      // The frame this update is already in paints the new look. The timer
      // from the previous pace must not hold that paint.
      _cancelPace();
      if (_shouldRun && !_clock.isRunning) _clock.start();
    }
  }

  @override
  void dispose() {
    _cancelPace();
    _ticker.removeListener(_haltAfterTick);
    _ticker.dispose();
    _deck.dispose();
    _disposeResources();
    _clock.stop();
    super.dispose();
  }

  void _schedulePace() {
    if (_paceCallbackScheduled) return;
    _paceCallbackScheduled = true;
    WidgetsBinding.instance.addPostFrameCallback((_) {
      _paceCallbackScheduled = false;
      _finishPace();
    });
  }

  /// Stops the ticker and arms one timer for the time until the next paint
  /// is due, minus [WeatherSkyBackground.paceLead]. An early tick uses the
  /// remainder the same way. A weather change has already cancelled the
  /// previous timer, so this arms the new look's interval.
  void _finishPace() {
    if (!mounted) return;
    _ticker.stop();
    if (!_shouldRun) {
      _cancelPace();
      return;
    }
    final since = _pacePainted ? Duration.zero : _seconds(_paceSincePaint);
    var wait = _paceInterval - since - WeatherSkyBackground.paceLead;
    if (wait < Duration.zero) wait = Duration.zero;
    _cancelPace();
    _paceTimer = Timer(wait, _onPaceFired);
  }

  void _onPaceFired() {
    _paceTimer = null;
    if (!mounted || !_shouldRun) return;
    if (!_clock.isRunning) _clock.start();
    _ticker.repeat();
  }

  Duration _seconds(double seconds) {
    if (!(seconds > 0)) return Duration.zero;
    return Duration(
      microseconds: (seconds * Duration.microsecondsPerSecond).round(),
    );
  }

  @override
  Widget build(BuildContext context) {
    final cache = _lutCache;
    if (cache == null || _shaders.length < _layerAssets.length) {
      return ColoredBox(color: _fallbackColour(widget.mode));
    }

    return LayoutBuilder(
      builder: (context, constraints) {
        final scale = _tier == RenderTier.low
            ? _renderScaleLow
            : _renderScaleHigh;
        // The picture is rasterized at this ratio. The deck records its own
        // image, so it has to apply the ratio itself or 0.4× lands in logical
        // pixels (about 0.15× of a 2.6× screen).
        final dpr = MediaQuery.devicePixelRatioOf(context);
        final painted = AnimatedBuilder(
          animation: _ticker,
          builder: (context, _) {
            final frame = _buildFrame();
            // Re-bakes only when the resolved keyframe has actually moved.
            cache.update(frame.sky);

            // Gap since the last picture we handed out. A skipped vsync must
            // not move this mark: particles integrate `dt`, not the clock, so
            // a mark that advanced on a skip would throw that time away and
            // slow the rain by the skip ratio.
            final sincePaint = frame.time - _lastFrameSeconds;
            final interval = skyFrameInterval(
              rain: frame.rain,
              snow: frame.snow,
              lightning: frame.lightning,
            );
            final due =
                sincePaint * Duration.microsecondsPerSecond >=
                interval.inMicroseconds;

            // While the animation is stopped (`active: false` — the sheet is
            // collapsed, or the sky sits under the scroll blur), the scene
            // cannot change, so a rebuilt painter is byte-identical. Handing
            // the *same* painter instance back lets RenderCustomPaint skip
            // the repaint on those rebuilds (it compares by identity) — the
            // scroll-driven rebuilds of the subtree above this widget
            // (`_ScrollBlurredWeather`) then cost an element update instead
            // of a full-screen shader stack re-render on every scroll tick.
            //
            // The same reuse applies when the pace interval has not elapsed.
            // Clouds, stars and the sun do not need a new picture every
            // vsync; rain, snow and a strike do. A weather change or a resume
            // paints on this frame anyway (`_paintNow`).
            final paint =
                _lastPainter == null || _paintNow || (widget.active && due);
            final WeatherSkyPainter painter;
            if (paint) {
              // Clamped so a dropped frame or a resume from background does
              // not teleport every particle down the screen in one step.
              // `sincePaint` is the whole gap, including skipped vsyncs.
              // Rain's 16 ms and snow's 33 ms stay under the cap, so a paced
              // step is not shortened.
              final dt = sincePaint.clamp(0.0, 1 / 20);
              _lastFrameSeconds = frame.time;
              _paintNow = false;
              painter = WeatherSkyPainter(
                shaders: _shaders,
                lutCache: cache,
                cloudSprites: _sprites,
                sunTextures: _sunTextures,
                frame: frame,
                rainField: _rain,
                snowField: _snow,
                dt: dt,
                deck: _deck,
                renderScale: scale,
                devicePixelRatio: dpr,
              );
            } else {
              painter = _lastPainter!;
            }
            _lastPainter = painter;
            // Build only records the pace. The post-frame callback stops the
            // ticker and arms the timer, which is what keeps the arm out of
            // build.
            _paceInterval = interval;
            _paceSincePaint = sincePaint;
            _pacePainted = paint;
            _schedulePace();
            // Its own layer, so a repaint of the sky stops at this boundary
            // instead of dirtying the layer it shares with the sheet's frosted
            // chrome and the map's overlay — on Home those are full-screen
            // offscreen passes, and re-rasterising them once per animated frame
            // is the single most expensive thing this widget can ask for.
            return RepaintBoundary(
              child: CustomPaint(size: Size.infinite, painter: painter),
            );
          },
        );

        if (!constraints.hasBoundedWidth || !constraints.hasBoundedHeight) {
          return painted;
        }

        // Rasterise the fast layers small and let the transform upscale.
        return ClipRect(
          child: Align(
            alignment: Alignment.topLeft,
            child: Transform.scale(
              scale: 1 / scale,
              alignment: Alignment.topLeft,
              filterQuality: FilterQuality.low,
              child: SizedBox(
                width: (constraints.maxWidth * scale).ceilToDouble(),
                height: (constraints.maxHeight * scale).ceilToDouble(),
                child: painted,
              ),
            ),
          ),
        );
      },
    );
  }

  SkyFrame _buildFrame() {
    final utc = AppTime.utc;
    final time =
        WeatherSkyBackground.debugFrameNow?.call() ??
        _clock.elapsedMilliseconds / 1000.0;

    final look = _lookFor(widget.mode);
    final frames = look.keyframes;
    // A live code's continuous channels win over the look's defaults — e.g.
    // 106 有雨 keeps the rain look's keyframes but runs 0.35 instead of the
    // fixed 小雨 rung. Snow is a separate field, so a rain-snow mix renders
    // both.
    final rain = widget.rainIntensity ?? look.rain;
    final snow = widget.snowIntensity ?? look.snow;

    _syncSky(utc, frames);

    return SkyFrame(
      time: time,
      sky: _sky!,
      cloudLayout: look.layout,
      cloudCoverage: look.coverage,
      rain: rain,
      snow: snow,
      fog: look.fog,
      rainbow: look.rainbow,
      wind: look.wind,
      lightning: look.lightning ? _lightningAt(time) : LightningFrame.none,
      moonPhase: _moon,
      keyframePosition: _position,
    );
  }

  /// Recomputes the sky pieces that have their own cadence — the sun anchor and
  /// moon phase once a day, the keyframe ring position once a minute — and
  /// caches them for the per-frame [SkyFrame] assembly.
  ///
  /// This is what keeps the per-frame cost of `_buildFrame` down to the parts
  /// that genuinely move every frame ([_lightningAt], particle time): before
  /// this, the ephemeris ran (and the LUT re-baked, see [_minuteKey]) on every
  /// tick.
  void _syncSky(DateTime utc, List<SkyKeyframe> frames) {
    final utcMs = utc.millisecondsSinceEpoch;
    final dayKey = utcMs ~/ 86400000;
    if (dayKey != _dayKey) {
      _dayKey = dayKey;
      // Anchor the ring to the day's real sunrise and sunset, so dawn keyframes
      // land at dawn in December as well as June.
      _sun = sunTimes(
        utc,
        latitude: widget.latitude,
        longitude: widget.longitude,
      );
      _moon = _moonPhase(utc);
    }
    // The local minute, from the UTC instant's epoch arithmetic rather than a
    // second `DateTime` per vsync: `AppTime.utc8` is exactly `utc + 8 h`, so
    // its epoch milliseconds are `utcMs + 28 800 000` and the wall-clock
    // `DateTime` is only needed — and only built — once a minute, below.
    final minuteKey = (utcMs + 8 * Duration.millisecondsPerHour) ~/ 60000;
    if (minuteKey != _minuteKey) {
      _minuteKey = minuteKey;
      final local = AppTime.taipei(utc);
      final hour =
          skyTimeHour(widget.timeMode) ?? (local.hour + local.minute / 60.0);
      _position = keyframePosition(
        hour,
        frameCount: frames.length,
        sunrise: _sun.sunrise,
        sunset: _sun.sunset,
      );
      _sky = resolveSky(frames, position: _position, humidity: widget.humidity);
    }
  }

  Color _fallbackColour(WeatherMode mode) => switch (mode) {
    WeatherMode.thunderstorm => const Color(0xFF2A2F3A),
    WeatherMode.rain => const Color(0xFF44505F),
    WeatherMode.fog => const Color(0xFF8A9099),
    _ => const Color(0xFF3F6DAE),
  };
}

