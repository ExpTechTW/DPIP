/// The app's spacing scale, in logical pixels.
///
/// Use these tokens for padding and gaps instead of bare numbers so layout
/// rhythm stays consistent. Based on a 4px grid.
abstract final class AppSpacing {
  /// 4 — hairline gaps.
  static const double xs = 4;

  /// 8 — tight padding / small gaps.
  static const double sm = 8;

  /// 12 — default gap between stacked items.
  static const double md = 12;

  /// 16 — default screen and card padding.
  static const double lg = 16;

  /// 24 — spacing between sections.
  static const double xl = 24;

  /// 32 — large section spacing.
  static const double xxl = 32;
}
