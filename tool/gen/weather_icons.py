#!/usr/bin/env python3
"""Builds the bundled weather icon font and its Dart constants.

Why this exists
---------------
Flutter's bundled `MaterialIcons-Regular.otf` has no rain glyph. It has
`ac_unit`, `snowing`, `thunderstorm`, `foggy` — and nothing for plain rain,
which in Taiwan is most of the weather. An earlier attempt papered over that by
declaring `IconData(0xf07c2)` and calling it `rainy`; that codepoint is
`Icons.severe_cold` in the bundled font, so every rainy hour rendered a
snowflake. Guessing a codepoint cannot be reviewed and does not fail loudly, so
this script removes the guess: glyphs are selected **by name** from Google's own
`.codepoints` manifest and the Dart constants are generated from the same
manifest, in the same run that builds the font.

What it produces
----------------
* `assets/fonts/DpipWeatherIcons.ttf` — Material Symbols Outlined, instantiated
  at one static style (wght 400, FILL 0, GRAD 0, opsz 24) and subset to the
  glyphs in `GLYPHS`. Roughly 20 KB, versus 10 MB for the variable font.
* `lib/core/weather/weather_icons.dart` — one `IconData` per glyph.

Material Symbols is Apache-2.0 (google/material-design-icons). It is an icon
*font asset*, not an icon package, so the "built-in Material icons only" rule in
CLAUDE.md still holds: nothing new is added to `pubspec.yaml`'s dependencies.

Running it
----------
Only needed when the glyph list changes. It needs `fonttools`, which is not a
project dependency — use a throwaway virtualenv:

    python3 -m venv /tmp/icons && /tmp/icons/bin/pip install fonttools
    /tmp/icons/bin/python tool/gen/weather_icons.py

The font and the Dart file are committed, so a normal build never runs this.
"""

from __future__ import annotations

import pathlib
import sys
import urllib.request

REPO = pathlib.Path(__file__).resolve().parent.parent
FONT_OUT = REPO / "assets" / "fonts" / "DpipWeatherIcons.ttf"
DART_OUT = REPO / "lib" / "core" / "weather" / "weather_icons.dart"

BASE = (
    "https://raw.githubusercontent.com/google/material-design-icons/"
    "master/variablefont/MaterialSymbolsOutlined"
    "%5BFILL%2CGRAD%2Copsz%2Cwght%5D"
)
FONT_URL = BASE + ".ttf"
CODEPOINTS_URL = BASE + ".codepoints"

# The style the icons are frozen at. Outlined / regular weight / optical size 24
# is what Flutter's own outlined icons are drawn at, so the weather glyphs sit
# beside `Icons.*_outlined` without looking like a different set.
INSTANCE = {"FILL": 0, "GRAD": 0, "opsz": 24, "wght": 400}

# (Material Symbols name, Dart constant, doc comment). Order is the order they
# appear in the generated file.
GLYPHS: list[tuple[str, str, str]] = [
    # — Sky, with the day/night pair the CWB families need —
    ("clear_day", "clearDay", "Clear sky by day — a plain sun."),
    ("clear_night", "clearNight", "Clear sky by night — a plain moon."),
    ("partly_cloudy_day", "partlyCloudyDay", "Sun behind a cloud (多雲, day)."),
    (
        "partly_cloudy_night",
        "partlyCloudyNight",
        "Moon behind a cloud (多雲, night).",
    ),
    ("cloudy", "cloudy", "Full cloud cover, no sun or moon (陰)."),
    # — Reduced visibility —
    ("mist", "mist", "Haze / light mist — horizontal streaks, no cloud."),
    ("foggy", "foggy", "A fog bank — denser than mist, drawn with a cloud."),
    # — Rain, three intensities —
    ("rainy_light", "rainyLight", "Light rain or a passing shower."),
    ("rainy", "rainy", "Steady rain — the everyday Taiwan glyph."),
    ("rainy_heavy", "rainyHeavy", "Torrential rain."),
    # — Frozen and mixed —
    ("rainy_snow", "rainySnow", "Rain and snow falling together (雨雪)."),
    ("weather_mix", "weatherMix", "Mixed showers — rain and snow, intermittent."),
    ("snowing", "snowing", "Snow."),
    ("snowing_heavy", "snowingHeavy", "Heavy snow."),
    ("weather_snowy", "weatherSnowy", "Snow grains / graupel."),
    ("snowflake", "snowflake", "Ice pellets — bare crystals, no cloud."),
    ("weather_hail", "weatherHail", "Hail."),
    ("cloudy_snowing", "cloudySnowing", "Snow from a storm cloud (雷雪)."),
    # — Electrical —
    ("bolt", "bolt", "Lightning or thunder with no precipitation."),
    ("thunderstorm", "thunderstorm", "Thunderstorm — rain and lightning."),
    ("storm", "storm", "A cyclonic storm."),
    # — Wind-borne —
    ("air", "air", "Wind or blowing dust."),
]

HEADER = '''/// Weather glyphs, from the bundled `DpipWeatherIcons` subset font.
///
/// **Generated by `tool/gen/weather_icons.py` — do not edit by hand.**
/// Every codepoint here was read from Google's `.codepoints` manifest in the
/// same run that built the font, because the alternative is guessing: this file
/// previously declared `rainy` as `0xf07c2`, which is `Icons.severe_cold` in
/// Flutter's bundled font, and so drew a snowflake on every rainy hour.
///
/// The font is Material Symbols Outlined (Apache-2.0), instantiated at one
/// static style and subset to the {count} glyphs below — an asset, not an icon
/// package, so it does not breach the built-in-icons-only rule. Flutter's own
/// `Icons` stay the source for everything that is not weather.
///
/// The mapping from a CWB weather code to one of these lives in
/// `weather_condition.dart`.
library;

import 'package:flutter/widgets.dart';

/// The family declared in `pubspec.yaml`.
const String weatherIconFont = 'DpipWeatherIcons';
'''


def fetch(url: str, cache: pathlib.Path) -> bytes:
    """Downloads `url`, reusing `cache` so a re-run is offline and instant."""
    if cache.exists():
        return cache.read_bytes()
    print(f"downloading {url}")
    data = urllib.request.urlopen(url).read()  # noqa: S310 — a pinned Google URL
    cache.parent.mkdir(parents=True, exist_ok=True)
    cache.write_bytes(data)
    return data


def main() -> int:
    try:
        from fontTools import subset
        from fontTools.ttLib import TTFont
        from fontTools.varLib import instancer
    except ImportError:
        print(__doc__.split("Running it")[1], file=sys.stderr)
        return 1

    cache = pathlib.Path(
        sys.argv[1] if len(sys.argv) > 1 else "/tmp/material-symbols"
    )
    codepoints_raw = fetch(CODEPOINTS_URL, cache / "symbols.codepoints").decode()
    font_bytes = fetch(FONT_URL, cache / "MaterialSymbolsOutlined.ttf")

    # name -> codepoint, straight from Google's manifest. A name that is not in
    # it is a typo or a removed icon; either way it must stop the build rather
    # than silently ship a missing glyph.
    table: dict[str, int] = {}
    for line in codepoints_raw.splitlines():
        name, _, code = line.partition(" ")
        if code:
            table[name] = int(code, 16)

    missing = [name for name, _, _ in GLYPHS if name not in table]
    if missing:
        print(f"not in Material Symbols: {', '.join(missing)}", file=sys.stderr)
        return 1

    wanted = {name: table[name] for name, _, _ in GLYPHS}
    # Distinct names can share a codepoint (`cloud`, `cloudy` and `cloud_queue`
    # are all f15c). Aliases are fine; two *different* pictures colliding is not,
    # and would show up here as a duplicate among names we chose deliberately.
    seen: dict[int, str] = {}
    for name, code in wanted.items():
        if code in seen:
            print(f"{name} and {seen[code]} are the same glyph", file=sys.stderr)
            return 1
        seen[code] = name

    font_path = cache / "MaterialSymbolsOutlined.ttf"
    font_path.write_bytes(font_bytes)
    font = TTFont(font_path)
    # Pin every axis, which drops fvar/gvar and most of the file with it.
    font = instancer.instantiateVariableFont(font, INSTANCE, inplace=True)

    options = subset.Options()
    options.layout_features = []
    options.name_IDs = ["*"]
    options.notdef_outline = True
    options.recalc_bounds = True
    subsetter = subset.Subsetter(options=options)
    subsetter.populate(unicodes=wanted.values())
    subsetter.subset(font)

    # Name the family so the pubspec declaration and the font agree.
    for record in font["name"].names:
        if record.nameID in (1, 4, 16):
            record.string = "DpipWeatherIcons"
        elif record.nameID in (2, 17):
            record.string = "Regular"
        elif record.nameID == 6:
            record.string = "DpipWeatherIcons-Regular"

    FONT_OUT.parent.mkdir(parents=True, exist_ok=True)
    font.save(FONT_OUT)

    lines = [HEADER.replace("{count}", str(len(GLYPHS)))]
    for name, dart, doc in GLYPHS:
        lines.append("")
        lines.append(f"/// {doc}")
        lines.append(f"/// Material Symbols `{name}`.")
        lines.append(
            f"const IconData {dart} = "
            f"IconData(0x{table[name]:x}, fontFamily: weatherIconFont);"
        )
    lines.append("")
    lines.append("/// Every glyph in the font, for the coverage test.")
    lines.append("const Map<String, IconData> weatherIconsByName = {")
    for name, dart, _ in GLYPHS:
        lines.append(f"  '{name}': {dart},")
    lines.append("};")
    lines.append("")
    DART_OUT.write_text("\n".join(lines))

    size = FONT_OUT.stat().st_size
    print(f"{FONT_OUT.relative_to(REPO)}: {len(GLYPHS)} glyphs, {size / 1024:.1f} KB")
    print(f"{DART_OUT.relative_to(REPO)}: regenerated")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
